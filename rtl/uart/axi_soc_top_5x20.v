// -----------------------------------------------------------------------------
// axi_soc_top_5x20.v                           (Verilog-2001, synthesizable)
//
// SoC integration top: axi_interconnect_wrap_5x20 (5 slave / 20 master ports)
//   + axi4_to_axi4lite_uart_adapter on M05
//   + axi_uart_top (axi-lite_uart-ipcore)
//
// All 5 slave ports (S00-S04) and 19 master ports (M00-M04, M06-M19)
// are brought straight out as top-level AXI4 ports for masters and peripherals.
// M05 is NOT brought out as raw AXI4: it is consumed internally by the UART
// adapter + UART IP, exposing only the UART pins (uart_rx_i / uart_tx_o /
// read_interrupt_o) at this level.
//
// Address map (defaults matching doc/SoC_IP_Registers_Summary.xlsx):
//   M00: IMEM    0x1000_0000 - 0x1000_FFFF (64KB)
//   M01: DMEM    0x1002_0000 - 0x1002_FFFF (64KB)
//   M02: I2C     0x4000_0000 - 0x4000_0FFF (4KB)
//   M03: PWM     0x4000_2000 - 0x4000_2FFF (4KB)
//   M04: SSD     0x4000_4000 - 0x4000_4FFF (4KB)
//   M05: UART    0x4000_6000 - 0x4000_6FFF (4KB)  <- Internal UART IP
//   M06: TIMER   0x4000_8000 - 0x4000_8FFF (4KB)
//   M07: GPIO    0x4000_A000 - 0x4000_AFFF (4KB)
//   M08: ICCM    0xEE00_0000 - 0xEE00_FFFF (64KB)
//   M09: DCCM    0xF004_0000 - 0xF004_FFFF (64KB)
//   M10: PIC     0xF00C_0000 - 0xF00C_7FFF (32KB)
//   M11-M19:     0x5000_0000 - 0x5800_0000 (16MB each, unassigned peripherals)
//
// Reset: rst is active-HIGH synchronous, shared by interconnect and adapter.
// uart_aresetn (registered ~rst, active-LOW) is generated by adapter.
// Clocking: axi_aclk_i and fixed_clk_i are driven by clk.
// -----------------------------------------------------------------------------
